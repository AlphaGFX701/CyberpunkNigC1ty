import { chromium } from '@playwright/test'
const browser = await chromium.launch({ channel: 'chrome', headless: true })
const page = await browser.newPage({ viewport: { width: 1440, height: 1080 } })
await page.goto('http://127.0.0.1:5180/?ui=1')
await page.getByRole('heading', { name: 'ชุดเครื่องมือของหน่วยกู้ระบบ' }).waitFor()
await page.evaluate(() => document.fonts.ready)
await page.screenshot({ path: 'evidence/ui-gallery.png' })
await page.screenshot({ path: 'evidence/ui-gallery-full.png', fullPage: true })
await page.locator('.button-lab').scrollIntoViewIfNeeded()
await page.screenshot({ path: 'evidence/ui-states.png' })
await page.setViewportSize({ width: 390, height: 844 })
await page.goto('http://127.0.0.1:5180/?ui=1')
await page.screenshot({ path: 'evidence/ui-narrow.png', fullPage: true })
await browser.close()
